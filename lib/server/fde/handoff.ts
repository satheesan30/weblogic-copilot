import { ARCHITECTURE_PATTERNS } from "@/lib/server/fde/catalog";
import { deliveryGaps } from "@/lib/fde/score";
import type { FdeUseCase } from "@/types/fde";

export function buildHandoffMarkdown(useCase: FdeUseCase) {
  const pattern = ARCHITECTURE_PATTERNS.find((item) => item.id === useCase.patternId);
  const gaps = deliveryGaps(useCase);

  return `# FDE handoff — ${useCase.title}

## Opportunity
- Owner: ${useCase.owner || "unassigned"}
- Team: ${useCase.team || "unassigned"}
- Stakeholders: ${useCase.stakeholders || "unlisted"}
- Stage: ${useCase.stage}
- Users: ${useCase.users || "unspecified"}

${useCase.problem || "_Problem statement missing._"}

## Approach decision
- Recommended path: **${useCase.recommendedApproach}**
- Impact ${useCase.impact}/5 · Data readiness ${useCase.dataReadiness}/5 · Risk ${useCase.risk}/5 · Complexity ${useCase.complexity}/5 · Latency sensitivity ${useCase.latencySensitivity}/5
- Judgment required: ${useCase.needsJudgment ? "yes" : "no"}
- Deterministic: ${useCase.deterministic ? "yes" : "no"}

${useCase.approachRationale}

## Architecture
- Workflow: ${useCase.workflow || "_missing_"}
- Integrations: ${useCase.integrations || "_missing_"}
- Data flows: ${useCase.dataFlows || "_missing_"}
- Operational / compliance: ${useCase.operationalNotes || "_missing_"}
- Reference pattern: ${pattern ? `${pattern.name} — ${pattern.whenToUse}` : "none selected"}

## Evaluation
${useCase.evaluationPlan || "_No offline/online/canary plan yet._"}

## Open gaps
${gaps.length ? gaps.map((gap) => `- ${gap}`).join("\n") : "- None recorded. Ready for stakeholder review."}

## Notes
${useCase.notes || "_None._"}

---
Generated by Agentci AI FDE desk. Do not include secrets in this pack.
`;
}
