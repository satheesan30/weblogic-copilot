import {
  assessEvidence,
  mergeChunks,
  refineQueryFromEvidence,
  scoreConfidence,
  searchKnowledge,
  searchMemory,
} from "@/lib/server/agent-tools";
import { shapeChatResponse } from "@/lib/server/chat-response";
import {
  buildContextualRetrievalQuery,
  buildSessionMemoryNote,
  normalizeHistory,
  shouldUseAgenticRag,
} from "@/lib/server/conversation";
import { addAgentMemory } from "@/lib/server/memory";
import { chatWithModel, chatWithModelStream } from "@/lib/server/ollama";
import { buildSpecialistRetrievalQuery, matchFdeSpecialist, routeSpecialistAgent } from "@/lib/server/specialists/orchestrator";
import { buildSpecialistSystemPrompt, buildSpecialistUserPrompt } from "@/lib/server/specialists/prompts";
import type { AgentStep, AppConfig, ChatApiRequest, ChatApiResponse, RetrievedChunk, RetrievedMemory } from "@/types/backend";

const MAX_RETRIEVAL_HOPS = 2;
const MAX_AGENT_STEPS = 10;

export async function runChatAgent(
  config: AppConfig,
  question: string,
  body: ChatApiRequest,
  ownerUsername: string,
  onToken?: (token: string) => void,
): Promise<ChatApiResponse> {
  const startedAt = Date.now();
  const steps: AgentStep[] = [];
  const history = normalizeHistory(body.history);
  const fdeRoute = matchFdeSpecialist(question, history);
  const useAgenticRag = shouldUseAgenticRag(question, history) || Boolean(fdeRoute);
  const specialistRoute = fdeRoute
    ? fdeRoute
    : useAgenticRag
      ? routeSpecialistAgent(question, history)
      : { specialist: "general" as const, label: "General Assistant", reason: "Non-operational question.", retrievalBoost: "" };
  const baseRetrievalQuery = buildContextualRetrievalQuery(question, history);
  const retrievalQuery = useAgenticRag
    ? buildSpecialistRetrievalQuery(baseRetrievalQuery, specialistRoute)
    : baseRetrievalQuery;
  let chunks: RetrievedChunk[] = [];
  let memories: RetrievedMemory[] = [];
  let retrievalWarning = "";

  steps.push({
    name: "Plan",
    status: "complete",
    detail: useAgenticRag
      ? `Agentic RAG with ${history.length} short-term turn(s). Routed to ${specialistRoute.label}.`
      : `General mode with ${history.length} short-term turn(s).`,
  });

  steps.push({
    name: "route_specialist",
    status: "complete",
    detail: `${specialistRoute.label}: ${specialistRoute.reason}`,
  });

  try {
    memories = await searchMemory(config, retrievalQuery, ownerUsername);
    steps.push({
      name: "search_memory",
      status: "complete",
      detail: memories.length ? `Found ${memories.length} long-term memory item(s).` : "No matching long-term memory found.",
    });
  } catch (error) {
    retrievalWarning = error instanceof Error ? `Memory retrieval failed: ${error.message}` : "Memory retrieval failed.";
    steps.push({ name: "search_memory", status: "warning", detail: retrievalWarning });
  }

  if (useAgenticRag) {
    const retrieval = await runAgenticRetrieval(config, question, retrievalQuery, ownerUsername, steps);
    chunks = retrieval.chunks;
    retrievalWarning = [retrievalWarning, retrieval.warning].filter(Boolean).join("\n");
  }

  let prompt = buildSpecialistUserPrompt(specialistRoute.specialist, question, chunks, memories);
  if (useAgenticRag && retrievalWarning) {
    prompt = `${prompt}\n\nRetrieval warning:\n${retrievalWarning}\nClearly state any missing evidence before giving guidance.`;
  }

  const promptMessages = [
    { role: "system" as const, content: buildSpecialistSystemPrompt(specialistRoute.specialist) },
    ...history,
    { role: "user" as const, content: prompt },
  ];
  const answer = onToken
    ? await chatWithModelStream(config, promptMessages, body.model, onToken)
    : await chatWithModel(config, promptMessages, body.model);

  steps.push({
    name: "generate_answer",
    status: "complete",
    detail: useAgenticRag
      ? `Answer generated by ${specialistRoute.label} with retrieved evidence.`
      : "Answer generated with short-term conversation history.",
  });

  const response = shapeChatResponse(answer, chunks);
  const confidence = useAgenticRag ? scoreConfidence(chunks, retrievalWarning) : undefined;

  if (useAgenticRag && config.memory.enabled && chunks.length) {
    try {
      await addAgentMemory(config, {
        ownerUsername,
        content: `[${specialistRoute.label}] ${buildSessionMemoryNote(question, answer, confidence)}`,
        category: "incident",
        source: "assistant",
      });
      steps.push({
        name: "write_long_term_memory",
        status: "complete",
        detail: "Saved an incident note to long-term agent memory for later turns.",
      });
    } catch (error) {
      steps.push({
        name: "write_long_term_memory",
        status: "warning",
        detail: error instanceof Error ? error.message : "Could not write long-term memory.",
      });
    }
  }

  return {
    ...response,
    confidence,
    agentTrace: {
      mode: useAgenticRag ? "agentic_rag" : "general",
      specialist: specialistRoute.specialist,
      specialistLabel: specialistRoute.label,
      maxSteps: MAX_AGENT_STEPS,
      elapsedMs: Date.now() - startedAt,
      steps,
    },
  };
}

async function runAgenticRetrieval(
  config: AppConfig,
  question: string,
  retrievalQuery: string,
  ownerUsername: string,
  steps: AgentStep[],
) {
  let warning = "";
  let chunks: RetrievedChunk[] = [];
  let activeQuery = retrievalQuery;

  for (let hop = 1; hop <= MAX_RETRIEVAL_HOPS; hop += 1) {
    try {
      const retrieved = await searchKnowledge(config, activeQuery, ownerUsername);
      chunks = mergeChunks(chunks, retrieved);
      const assessment = assessEvidence(chunks);
      steps.push({
        name: hop === 1 ? "search_knowledge" : "search_knowledge_refined",
        status: assessment.sufficient ? "complete" : "warning",
        detail: `Hop ${hop}/${MAX_RETRIEVAL_HOPS} query="${activeQuery.slice(0, 120)}". ${assessment.detail}`,
      });

      steps.push({
        name: "assess_evidence",
        status: assessment.sufficient ? "complete" : "warning",
        detail: assessment.sufficient
          ? "Evidence is sufficient for the specialist to answer."
          : "Evidence is weak; applying deterministic evidence refinement if hops remain.",
      });

      if (assessment.sufficient || hop >= MAX_RETRIEVAL_HOPS) {
        if (!assessment.sufficient) {
          steps.push({
            name: "evidence_gate",
            status: "warning",
            detail: "Max retrieval hops reached with weak evidence. Final answer must request missing logs instead of guessing.",
          });
        }
        break;
      }

      activeQuery = refineQueryFromEvidence(question, chunks);
      steps.push({
        name: "refine_query",
        status: "complete",
        detail: `Deterministically refined retrieval query: ${activeQuery.slice(0, 180)}`,
      });
    } catch (error) {
      warning = error instanceof Error ? error.message : "Document retrieval is unavailable.";
      steps.push({
        name: hop === 1 ? "search_knowledge" : "search_knowledge_refined",
        status: "warning",
        detail: warning,
      });
      break;
    }
  }

  return { chunks, warning };
}
